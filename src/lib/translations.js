export function getLocaleFromUrl(urlOrAstro) {
  // Accept either Astro object or URL for backward compatibility
  let pathname;
  let locals;

  if (urlOrAstro && typeof urlOrAstro === 'object' && 'locals' in urlOrAstro) {
    // It's the Astro object - check locals first (set by middleware)
    locals = urlOrAstro.locals;
    if (locals && locals.locale) {
      return locals.locale;
    }
    pathname = urlOrAstro.url.pathname;
  } else {
    // It's a URL object or string
    pathname = typeof urlOrAstro === "string" ? urlOrAstro : urlOrAstro.pathname;
  }

  const normalized = pathname.replace(/^\//, "");
  if (normalized.startsWith("en/") || normalized === "en") {
    return "en";
  }
  if (normalized.startsWith("id/") || normalized === "id") {
    return "id";
  }
  return defaultLang;
}

